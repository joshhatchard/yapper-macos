import AppKit
import Carbon.HIToolbox

/// `PasteAPI` over `NSPasteboard` and a synthetic Cmd-V posted with `CGEvent`.
///
/// The previous pasteboard contents (every item and type) are saved first and written back after
/// `restoreDelay`, which gives the target app time to read the pasteboard while it handles Cmd-V.
/// If the pasteboard changed meanwhile (the user copied something), it is left alone.
/// The transcript is marked transient/concealed (nspasteboard.org conventions) so clipboard
/// managers that honour those markers do not record it. Posting keys needs Accessibility trust,
/// which insertion already requires.
@MainActor
final class SystemPaste: PasteAPI {
    static let defaultRestoreDelay: Duration = .milliseconds(500)
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private let pasteboard: NSPasteboard
    private let restoreDelay: Duration
    private let postKeystroke: @MainActor () throws(PasteError) -> Void
    private let secureInput: @MainActor () -> Bool

    init(
        pasteboard: NSPasteboard = .general,
        restoreDelay: Duration = SystemPaste.defaultRestoreDelay,
        postKeystroke: @escaping @MainActor () throws(PasteError) -> Void = SystemPaste.postCommandV,
        isSecureInputActive: @escaping @MainActor () -> Bool = { IsSecureEventInputEnabled() }
    ) {
        self.pasteboard = pasteboard
        self.restoreDelay = restoreDelay
        self.postKeystroke = postKeystroke
        self.secureInput = isSecureInputActive
    }

    var isSecureInputActive: Bool { secureInput() }

    func paste(_ text: String) async throws(PasteError) {
        let saved = snapshot()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in [Self.transientType, Self.concealedType, Self.autoGeneratedType] {
            item.setData(Data(), forType: marker)
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            restore(saved)
            throw .pasteboardWriteFailed
        }
        let written = pasteboard.changeCount
        do {
            try postKeystroke()
        } catch {
            restore(saved)
            throw error
        }
        try? await Task.sleep(for: restoreDelay)
        if pasteboard.changeCount == written { restore(saved) }
    }

    /// Posts Cmd-V (ANSI V key code) with only Command held, so physically held modifiers such as
    /// Shift do not turn it into a different shortcut. Non-QWERTY layouts that move V are not handled.
    static func postCommandV() throws(PasteError) {
        let source = CGEventSource(stateID: .privateState)
        let key = CGKeyCode(kVK_ANSI_V)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
            let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        else { throw .keystrokeFailed }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cgSessionEventTap)
        up.post(tap: .cgSessionEventTap)
    }

    private func snapshot() -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private func restore(_ saved: Snapshot) {
        pasteboard.clearContents()
        let items = saved.filter { !$0.isEmpty }.map { pairs in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}
